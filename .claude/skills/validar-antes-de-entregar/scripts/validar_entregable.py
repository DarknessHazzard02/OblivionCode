# -*- coding: utf-8 -*-
"""Validación profunda de entregables antes de liberarlos.

Tres capas, en este orden:
  1. PROCEDENCIA  - ningún rastro de quién o qué generó el archivo.
  2. INTEGRIDAD   - el archivo de verdad abre, y su contenido se puede leer y dibujar.
  3. CONTENIDO    - dice lo que debe decir: sin marcadores de relleno ni páginas en blanco.

Uso:
    python validar_entregable.py ARCHIVO [ARCHIVO ...] [--fix] [--owner "Área"] [--json out.json]

--fix reescribe los metadatos con el valor de --owner y quita los caracteres invisibles
(en Office y en archivos de texto; en PDF solo se reportan). Sin --fix solo reporta.
Devuelve 0 si no hay hallazgos, 1 si los hay. Úsalo en un paso previo a entregar.
"""
import argparse, io, json, os, re, sys, zipfile

try:
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
except Exception:
    pass

# Rastros que delatan la herramienta o el asistente. Se buscan en TODO el binario,
# no solo en los campos de metadatos, porque ahí es donde de verdad se esconden.
RASTROS = [
    r'claude', r'anthropic', r'openai', r'chatgpt', r'gpt-4', r'copilot', r'gemini',
    r'python-docx', r'openpyxl', r'pymupdf', r'mupdf', r'reportlab', r'xlsxwriter',
    r'python-pptx', r'matplotlib', r'libreoffice', r'generated by', r'created with',
    r'ai[- ]generated', r'language model',
]
# Marcadores de relleno que nunca deben llegar a un entregable.
RELLENO = [
    r'\bTODO\b', r'\bTBD\b', r'\bFIXME\b', r'\bXXX\b', r'lorem ipsum',
    r'\bPLACEHOLDER\b', r'\[insert', r'\bpendiente de llenar\b', r'\bpor definir\b',
    r'sample text', r'texto de ejemplo', r'<<[^>]+>>',
]

OOXML = ('.docx', '.xlsx', '.pptx', '.vsdx', '.dotx', '.xlsm', '.potx')
TEXTO = ('.html', '.htm', '.md', '.txt', '.svg', '.csv', '.json', '.xml', '.js', '.css', '.py')

# Caracteres invisibles. No se ven en ningun visor, pero viajan con el texto: pueden
# esconder texto entero (etiquetas Unicode), invertir el orden en que se lee el codigo
# (controles bidi, "Trojan Source") o marcar de donde salio un texto copiado.
# La MISMA lista vive en portal-seguridad/scripts/revisar_rastros.py: si cambia aqui,
# se cambia alla.
INVISIBLES = (
    [(0x00AD, 0x00AD), (0x034F, 0x034F), (0x061C, 0x061C), (0x115F, 0x1160), (0x17B4, 0x17B5),
     (0x180E, 0x180E), (0x200B, 0x200F), (0x202A, 0x202E), (0x2060, 0x2064), (0x2066, 0x206F),
     (0x2800, 0x2800), (0x3164, 0x3164), (0xFE00, 0xFE0F), (0xFEFF, 0xFEFF), (0xFFA0, 0xFFA0),
     (0xE0000, 0xE007F), (0xE0100, 0xE01EF)])
GRAVES = [(0x202A, 0x202E), (0x2066, 0x2069), (0xE0000, 0xE007F)]   # esconden o reordenan texto

def _en(cp, rangos):
    return any(a <= cp <= b for a, b in rangos)

def _es_emoji(ch):
    import unicodedata
    cp = ord(ch)
    return cp >= 0x1F000 or 0x2100 <= cp <= 0x2BFF or unicodedata.category(ch).startswith('S')

def invisibles(texto):
    """[(linea, columna, codigo, nombre)] de cada caracter invisible que NO tiene uso legitimo.

    Legitimos: el BOM al inicio del archivo (los CSV lo llevan a proposito para Excel), y el
    selector de variacion y el union de ancho cero dentro de un emoji compuesto (el ⚠️ lleva FE0F).
    """
    import unicodedata
    salida = []
    linea, col = 1, 0
    for i, ch in enumerate(texto):
        if ch == '\n':
            linea, col = linea + 1, 0
            continue
        col += 1
        cp = ord(ch)
        if cp < 0xAD or not _en(cp, INVISIBLES):
            continue
        previo = texto[i - 1] if i else ''
        siguiente = texto[i + 1] if i + 1 < len(texto) else ''
        if cp == 0xFEFF and (i == 0 or (previo and previo in "'\"`,")):
            continue  # BOM al inicio, o escrito a proposito en un literal ('﻿' + csv)
        if cp in (0xFE0E, 0xFE0F) and previo and (_es_emoji(previo) or previo in '#*0123456789'):
            continue
        if cp == 0x200D and previo and siguiente and (_es_emoji(previo) or ord(previo) == 0xFE0F) and _es_emoji(siguiente):
            continue
        salida.append((linea, col, cp, unicodedata.name(ch, 'U+%04X' % cp)))
    return salida

def texto_escondido(texto):
    """Las etiquetas Unicode (U+E0020-U+E007E) codifican ASCII invisible: se decodifica para mostrarlo."""
    oculto = ''.join(chr(ord(c) - 0xE0000) for c in texto if 0xE0020 <= ord(c) <= 0xE007E)
    return oculto

def _reportar_invisibles(texto, origen, rep):
    hallados = invisibles(texto)
    if not hallados:
        return
    graves = [h for h in hallados if _en(h[2], GRAVES)]
    tipos = {}
    for h in hallados:
        tipos.setdefault('U+%04X %s' % (h[2], h[3]), []).append('%d:%d' % (h[0], h[1]))
    detalle = '; '.join('%s x%d (en %s%s)' % (t, len(p), ', '.join(p[:3]), '...' if len(p) > 3 else '')
                        for t, p in list(tipos.items())[:6])
    oculto = texto_escondido(texto)
    rep.add('procedencia', 'alta' if graves else 'media',
            '%s%d caracter(es) invisible(s)%s: %s' % (
                ('TEXTO ESCONDIDO %r | ' % oculto[:80]) if oculto else '',
                len(hallados), ' en ' + origen if origen else '', detalle))

def quitar_invisibles(texto):
    quitar = {(h[0], h[1]) for h in invisibles(texto)}
    if not quitar:
        return texto
    salida, linea, col = [], 1, 0
    for ch in texto:
        if ch == '\n':
            linea, col = linea + 1, 0
            salida.append(ch)
            continue
        col += 1
        if (linea, col) not in quitar:
            salida.append(ch)
    return ''.join(salida)

class Reporte:
    def __init__(self, path):
        self.path = path
        self.hallazgos = []      # (capa, severidad, mensaje)
        self.datos = {}

    def add(self, capa, sev, msg):
        self.hallazgos.append({'capa': capa, 'severidad': sev, 'mensaje': msg})

    @property
    def ok(self):
        return not any(h['severidad'] == 'alta' for h in self.hallazgos)

# ---------------------------------------------------------------- capa 1
def _buscar(texto, patrones, etiqueta, rep, capa, sev, origen=''):
    vistos = set()
    for pat in patrones:
        for m in re.finditer(pat, texto, re.I):
            frag = m.group(0)
            clave = (pat, frag.lower())
            if clave in vistos:
                continue
            vistos.add(clave)
            ctx = texto[max(0, m.start() - 45):m.start() + 45].replace('\n', ' ')
            rep.add(capa, sev, '%s: %r%s  ...%s...' % (etiqueta, frag,
                                                       ' en ' + origen if origen else '', ctx.strip()))

def procedencia(path, rep):
    ext = os.path.splitext(path)[1].lower()
    if ext in OOXML:
        with zipfile.ZipFile(path) as z:
            for n in z.namelist():
                try:
                    txt = z.read(n).decode('utf8', 'ignore')
                except Exception:
                    continue
                _buscar(txt, RASTROS, 'rastro de herramienta', rep, 'procedencia', 'alta', n)
                if n.endswith('.xml'):
                    _reportar_invisibles(txt, n, rep)
        _props_ooxml(path, rep)
    else:
        raw = open(path, 'rb').read().decode('utf8', 'ignore')
        _buscar(raw, RASTROS, 'rastro de herramienta', rep, 'procedencia', 'alta')
        if ext in TEXTO:
            _reportar_invisibles(raw, '', rep)
        if ext == '.pdf':
            _props_pdf(path, rep)
            try:
                import fitz
                d = fitz.open(path)
                for i, pg in enumerate(d):
                    _reportar_invisibles(pg.get_text(), 'la pagina %d' % (i + 1), rep)
            except Exception:
                rep.add('procedencia', 'media', 'no se pudo extraer el texto del PDF para buscar caracteres invisibles')

def _props_ooxml(path, rep):
    campos = {}
    with zipfile.ZipFile(path) as z:
        for n in ('docProps/core.xml', 'docProps/app.xml'):
            if n not in z.namelist():
                continue
            x = z.read(n).decode('utf8', 'ignore')
            for tag in ('dc:creator', 'cp:lastModifiedBy', 'dc:title', 'dc:description',
                        'Application', 'Company', 'Manager'):
                m = re.search(r'<%s(?:\s[^>]*)?>(.*?)</%s>' % (tag, tag), x, re.S)
                if m and m.group(1).strip():
                    campos[tag] = m.group(1).strip()
    rep.datos['propiedades'] = campos

def _props_pdf(path, rep):
    try:
        import fitz
    except ImportError:
        rep.add('procedencia', 'media', 'PyMuPDF no instalado: no se revisaron los metadatos del PDF')
        return
    d = fitz.open(path)
    rep.datos['propiedades'] = {k: v for k, v in d.metadata.items() if v}
    raw = open(path, 'rb').read()
    # el comentario de cabecera y un /Producer dentro del catálogo no salen en las propiedades
    if re.search(rb'%\s*(Written|Created|Produced) by', raw, re.I):
        rep.add('procedencia', 'alta', 'comentario de cabecera con el nombre de la herramienta')
    for m in re.finditer(rb'/(Producer|Creator)\s*\(([^)]*)\)', raw):
        val = m.group(2).decode('utf8', 'ignore').strip()
        if not val:
            continue
        rep.datos.setdefault('pdf_internos', {})[m.group(1).decode()] = val
        # solo es hallazgo si el valor delata una herramienta; si ya trae el nombre
        # del área es justamente lo que queremos
        if any(re.search(pat, val, re.I) for pat in RASTROS):
            rep.add('procedencia', 'alta',
                    '/%s escondido en el cuerpo del PDF: %r' % (m.group(1).decode(), val))

# ---------------------------------------------------------------- capa 2
def integridad(path, rep):
    ext = os.path.splitext(path)[1].lower()
    if ext in OOXML:
        with zipfile.ZipFile(path) as z:
            if z.testzip() is not None:
                rep.add('integridad', 'alta', 'el paquete zip está corrupto')
                return
            from xml.etree import ElementTree as ET
            for n in z.namelist():
                if n.endswith('.xml') or n.endswith('.rels'):
                    try:
                        ET.fromstring(z.read(n))
                    except Exception as e:
                        rep.add('integridad', 'alta', 'XML inválido en %s: %s' % (n, e))
    if ext == '.docx':
        _abrir(rep, 'Word', lambda: __import__('docx').Document(path),
               lambda d: {'parrafos': len(d.paragraphs), 'tablas': len(d.tables),
                          'caracteres': sum(len(p.text) for p in d.paragraphs)})
    elif ext in ('.xlsx', '.xlsm'):
        _abrir(rep, 'Excel', lambda: __import__('openpyxl').load_workbook(path),
               lambda w: {'hojas': w.sheetnames,
                          'filas': {s.title: s.max_row for s in w.worksheets}})
    elif ext == '.vsdx':
        try:
            import vsdx
            with vsdx.VisioFile(path) as v:
                rep.datos['visio'] = {'paginas': [p.name for p in v.pages],
                                      'formas': len(v.pages[0].child_shapes)}
        except ImportError:
            rep.add('integridad', 'media', 'librería vsdx no instalada: no se abrió el archivo de Visio')
        except Exception as e:
            rep.add('integridad', 'alta', 'Visio no se pudo leer: %s' % e)
    elif ext in ('.pdf', '.svg'):
        _render(path, rep)

def _abrir(rep, etiqueta, abrir, resumir):
    try:
        obj = abrir()
    except ImportError as e:
        rep.add('integridad', 'media', 'no se pudo verificar %s: %s' % (etiqueta, e))
        return
    except Exception as e:
        rep.add('integridad', 'alta', '%s no abre: %s' % (etiqueta, e))
        return
    try:
        rep.datos[etiqueta.lower()] = resumir(obj)
    except Exception as e:
        rep.add('integridad', 'media', 'abrió pero no se pudo resumir: %s' % e)

def _render(path, rep):
    """Dibujar de verdad cada página. Un archivo puede 'abrir' y aun así salir en blanco."""
    try:
        import fitz
    except ImportError:
        rep.add('integridad', 'media', 'PyMuPDF no instalado: no se dibujó el archivo')
        return
    try:
        d = fitz.open(path)
    except Exception as e:
        rep.add('integridad', 'alta', 'no abre: %s' % e)
        return
    paginas = []
    for i, pg in enumerate(d):
        try:
            pm = pg.get_pixmap(dpi=50)
        except Exception as e:
            rep.add('integridad', 'alta', 'la página %d no se puede dibujar: %s' % (i + 1, e))
            continue
        # ¿salió en blanco? hay que mirar el pixmap completo: en un diagrama ancho
        # la esquina superior izquierda es margen y siempre sería de un solo color.
        # El texto extraíble también cuenta como prueba de que sí se dibujó algo.
        blanca = len(set(pm.samples)) <= 1 and len(pg.get_text().strip()) == 0
        if blanca:
            rep.add('contenido', 'alta', 'la página %d sale en blanco' % (i + 1))
        paginas.append({'pagina': i + 1,
                        'mm': [round(pg.rect.width / 72 * 25.4), round(pg.rect.height / 72 * 25.4)],
                        'caracteres': len(pg.get_text()), 'blanca': blanca})
    rep.datos['paginas'] = paginas
    if d.page_count and all(p['caracteres'] < 20 for p in paginas):
        rep.add('contenido', 'media',
                'casi no hay texto extraíble: puede que sea una imagen y no texto vectorial')

# ---------------------------------------------------------------- capa 3
def contenido(path, rep):
    ext = os.path.splitext(path)[1].lower()
    textos = []
    if ext == '.docx':
        try:
            d = __import__('docx').Document(path)
            textos = [p.text for p in d.paragraphs]
            for t in d.tables:
                for row in t.rows:
                    textos += [c.text for c in row.cells]
        except Exception:
            pass
    elif ext in ('.xlsx', '.xlsm'):
        try:
            wb = __import__('openpyxl').load_workbook(path, data_only=True)
            for ws in wb.worksheets:
                for row in ws.iter_rows(values_only=True):
                    textos += [str(c) for c in row if c is not None]
        except Exception:
            pass
    elif ext in ('.pdf', '.svg'):
        try:
            import fitz
            d = fitz.open(path)
            textos = [pg.get_text() for pg in d]
        except Exception:
            pass
    elif ext in ('.html', '.htm', '.md', '.txt'):
        textos = [open(path, encoding='utf8', errors='ignore').read()]
    _buscar('\n'.join(textos), RELLENO, 'marcador de relleno', rep, 'contenido', 'alta')

# ---------------------------------------------------------------- arreglo
APP_POR_EXT = {'.docx': 'Microsoft Office Word', '.dotx': 'Microsoft Office Word',
               '.xlsx': 'Microsoft Excel', '.xlsm': 'Microsoft Excel',
               '.pptx': 'Microsoft Office PowerPoint', '.potx': 'Microsoft Office PowerPoint',
               '.vsdx': 'Microsoft Visio'}

def arreglar(path, owner):
    """Reescribe los metadatos.

    En PDF hay una trampa: guardar de forma incremental (saveIncr) NO borra los bytes
    viejos, solo añade una revisión encima, así que el autor anterior se queda dentro del
    archivo y cualquiera lo encuentra. Por eso se reescribe completo con garbage+clean.
    El parche por bytes queda solo para el comentario de cabecera, y ahí la sustitución
    tiene que ser del mismo largo porque mover un byte rompe la tabla xref.
    """
    ext = os.path.splitext(path)[1].lower()
    if ext in OOXML:
        tmp = path + '.tmp'
        with zipfile.ZipFile(path) as zin, zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                data = zin.read(item.filename)
                if item.filename == 'docProps/core.xml':
                    x = data.decode('utf8')
                    for tag, val in (('dc:creator', owner), ('cp:lastModifiedBy', owner),
                                     ('dc:description', ''), ('cp:keywords', '')):
                        x = _set_tag(x, tag, val)
                    data = x.encode('utf8')
                elif item.filename == 'docProps/app.xml':
                    x = data.decode('utf8')
                    x = _set_tag(x, 'Application', APP_POR_EXT.get(ext, 'Microsoft Office'))
                    x = _set_tag(x, 'Manager', '')
                    data = x.encode('utf8')
                if item.filename.endswith('.xml'):
                    # los invisibles van dentro del texto, nunca en la sintaxis del XML:
                    # quitarlos no cambia la estructura
                    x = data.decode('utf8', 'ignore')
                    limpio = quitar_invisibles(x)
                    if limpio != x:
                        data = limpio.encode('utf8')
                zout.writestr(item, data)
        os.replace(tmp, path)
        return True

    if ext in TEXTO:
        raw = open(path, 'rb').read()
        texto = raw.decode('utf8', 'ignore')
        limpio = quitar_invisibles(texto)
        if limpio != texto:
            open(path, 'wb').write(limpio.encode('utf8'))
        return True

    if ext == '.pdf':
        try:
            import fitz
        except ImportError:
            return False
        d = fitz.open(path)
        md = dict(d.metadata or {})
        md.update({'author': owner, 'producer': owner, 'creator': owner, 'keywords': ''})
        d.set_metadata(md)
        tmp = path + '.tmp'
        d.save(tmp, garbage=4, deflate=True, clean=True)   # reescritura completa
        d.close()
        os.replace(tmp, path)
        raw = open(path, 'rb').read()
        out = re.sub(rb'%\s*(?:Written|Created|Produced) by [^\r\n]*',
                     lambda m: b'%' + b' ' * (len(m.group(0)) - 1), raw)
        # MuPDF vuelve a escribir su nombre en un /Producer dentro del objeto catálogo
        # cada vez que guarda. Se neutraliza con espacios del mismo largo.
        def _neutro(m):
            val = m.group(2)
            if any(re.search(pat, val.decode('utf8', 'ignore'), re.I) for pat in RASTROS):
                return b'/' + m.group(1) + b'(' + b' ' * len(val) + b')'
            return m.group(0)
        out = re.sub(rb'/(Producer|Creator)\s*\(([^)]*)\)', _neutro, out)
        if out != raw:
            assert len(out) == len(raw), 'cambió el largo: rompería la tabla xref'
            open(path, 'wb').write(out)
        return True
    return False

def _set_tag(xml, tag, value):
    if re.search(r'<%s\s*/>' % tag, xml):
        return re.sub(r'<%s\s*/>' % tag, '<%s>%s</%s>' % (tag, value, tag), xml, count=1)
    if re.search(r'<%s[ >]' % tag, xml):
        return re.sub(r'<%s(\s[^>]*)?>.*?</%s>' % (tag, tag),
                      lambda m: '<%s%s>%s</%s>' % (tag, m.group(1) or '', value, tag),
                      xml, count=1, flags=re.S)
    return xml

# ---------------------------------------------------------------- main
def revisar(path, owner=None, fix=False):
    rep = Reporte(path)
    if not os.path.exists(path):
        rep.add('integridad', 'alta', 'el archivo no existe')
        return rep
    if fix and owner:
        arreglar(path, owner)
    for f in (procedencia, integridad, contenido):
        try:
            f(path, rep)
        except Exception as e:
            rep.add(f.__name__, 'media', 'la revisión falló: %s' % e)
    return rep

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('archivos', nargs='+')
    ap.add_argument('--owner', default=None, help='con qué nombre se reemplaza el autor')
    ap.add_argument('--fix', action='store_true', help='limpia metadatos antes de revisar')
    ap.add_argument('--json', default=None)
    a = ap.parse_args()

    if a.fix and not a.owner:
        ap.error('--fix necesita --owner')

    salida, malos = [], 0
    for p in a.archivos:
        rep = revisar(p, a.owner, a.fix)
        salida.append({'archivo': p, 'ok': rep.ok, 'hallazgos': rep.hallazgos, 'datos': rep.datos})
        marca = 'OK  ' if rep.ok else 'FALLA'
        print('%s  %s' % (marca, p))
        for k, v in rep.datos.items():
            print('        %s: %s' % (k, json.dumps(v, ensure_ascii=False)[:160]))
        for h in rep.hallazgos:
            print('        [%s/%s] %s' % (h['capa'], h['severidad'], h['mensaje'][:180]))
        if not rep.ok:
            malos += 1
    if a.json:
        io.open(a.json, 'w', encoding='utf8').write(json.dumps(salida, ensure_ascii=False, indent=1))
    print('\n%d archivo(s), %d con hallazgos de severidad alta' % (len(a.archivos), malos))
    return 1 if malos else 0

if __name__ == '__main__':
    sys.exit(main())
