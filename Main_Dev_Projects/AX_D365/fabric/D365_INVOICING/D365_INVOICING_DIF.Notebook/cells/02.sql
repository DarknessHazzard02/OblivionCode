
%%sql
-- Updated by Haz
-- Appends to D365_INVOICING the last-5-days lines (D365_INVOICING_5D) it does not have yet,
-- matched by order, line and actual shipment date and time
REFRESH TABLE CMA_BI_LAKE.D365_INVOICING;
REFRESH TABLE CMA_BI_LAKE.D365_INVOICING_5D;

DROP VIEW IF EXISTS D365_INVOICING_view;
DROP VIEW IF EXISTS D365_INVOICING_5D_view;

CREATE OR REPLACE TEMP VIEW D365_INVOICING_view AS
SELECT * FROM CMA_BI_LAKE.D365_INVOICING;

CREATE OR REPLACE TEMP VIEW D365_INVOICING_5D_view AS
SELECT * FROM CMA_BI_LAKE.D365_INVOICING_5D;

INSERT INTO CMA_BI_LAKE.D365_INVOICING (
    DATA_BASE,
    ORGANIZATION_CODE,
    ORGANIZATION_NAME,
    DIVISION,
    CUSTOMER_NAME,
    CUSTOMER_NUMBER,
    ORDER_NUMBER,
    ORDER_LINE_NUMBER,
    CUST_PO_NUMBER,
    `BILL OF LADING ID`,
    DELIVERY_NUMBER,
    ITEM_NUMBER,
    DESCRIPTION,
    QUANTITY,
    WAYBILL_AIRBILL,
    SALESPRICE,
    AMOUNT,
    `SHIPPING STATE`,
    FREIGHT_CARRIER_CODE,
    REQUEST_DATE,
    SCHEDULE_SHIP_DATE,
    RELEASE_TO_WAREHOUSE_DATE,
    RELEASE_TO_WAREHOUSE_TIME,
    SHIP_CONFIRM_DATE,
    ACTUAL_SHIPMENT_DATE,
    ACTUAL_SHIPMENT_TIME,
    `MEET REQ. SHIP DATE`,
    `MEET SCHED. SHIP DATE`,
    `DELIVERY REASON`,
    DELIVERY_STREET,
    DELIVERY_CITY,
    DELIVERY_STATE,
    DELIVERY_ZIPCODE,
    DELIVERY_COUNTRY,
    EXECUTION_DATE,
    EXECUTION_TIME
)
SELECT
    sd.DATA_BASE,
    sd.ORGANIZATION_CODE,
    sd.ORGANIZATION_NAME,
    sd.DIVISION,
    sd.CUSTOMER_NAME,
    sd.CUSTOMER_NUMBER,
    sd.ORDER_NUMBER,
    sd.ORDER_LINE_NUMBER,
    sd.CUST_PO_NUMBER,
    sd.`BILL OF LADING ID`,
    sd.DELIVERY_NUMBER,
    sd.ITEM_NUMBER,
    sd.DESCRIPTION,
    sd.QUANTITY,
    sd.WAYBILL_AIRBILL,
    sd.SALESPRICE,
    sd.AMOUNT,
    sd.`SHIPPING STATE`,
    sd.FREIGHT_CARRIER_CODE,
    sd.REQUEST_DATE,
    sd.SCHEDULE_SHIP_DATE,
    sd.RELEASE_TO_WAREHOUSE_DATE,
    sd.RELEASE_TO_WAREHOUSE_TIME,
    sd.SHIP_CONFIRM_DATE,
    sd.ACTUAL_SHIPMENT_DATE,
    sd.ACTUAL_SHIPMENT_TIME,
    sd.`MEET REQ. SHIP DATE`,
    sd.`MEET SCHED. SHIP DATE`,
    sd.`DELIVERY REASON`,
    sd.DELIVERY_STREET,
    sd.DELIVERY_CITY,
    sd.DELIVERY_STATE,
    sd.DELIVERY_ZIPCODE,
    sd.DELIVERY_COUNTRY,
    sd.EXECUTION_DATE,
    sd.EXECUTION_TIME
FROM D365_INVOICING_5D_view sd
LEFT ANTI JOIN D365_INVOICING_view t2
ON  sd.ORDER_NUMBER = t2.ORDER_NUMBER
AND sd.ORDER_LINE_NUMBER = t2.ORDER_LINE_NUMBER
AND sd.ACTUAL_SHIPMENT_DATE = t2.ACTUAL_SHIPMENT_DATE
AND sd.ACTUAL_SHIPMENT_TIME = t2.ACTUAL_SHIPMENT_TIME;

